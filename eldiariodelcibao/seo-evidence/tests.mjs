import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { reportForKeywords } from "./engine.mjs";

const here=dirname(fileURLToPath(import.meta.url));
const keywords=JSON.parse(readFileSync(join(here,"keywords.json"),"utf8"));
const now="2026-10-12T12:00:00Z";
const sample=keywords[0].keyword;
const empty=reportForKeywords({keywords,now});
assert.equal(keywords.length,10);
assert.equal(empty.totalKeywords,10);
assert.equal(empty.summary.unverified,10);
assert.equal(empty.summary.googleVolumesWithEvidence,0);
assert.equal(empty.rows[0].volume.avgMonthlySearches,null);
assert.equal(empty.rows[0].difficulty.difficultySeo,null);
const ads={source:"Google Ads KeywordPlanIdeaService.GenerateKeywordHistoricalMetrics",geo:"DO",language:"es",network:"GOOGLE_SEARCH",capturedAt:now,results:[{text:sample,keywordMetrics:{avgMonthlySearches:1900,competitionIndex:96,competition:"HIGH"}}]};
const adsReport=reportForKeywords({keywords,ads,now});
assert.equal(adsReport.rows[0].volume.avgMonthlySearches,1900);
assert.equal(adsReport.rows[0].volume.competitionIndexAds,96);
assert.equal(adsReport.rows[0].difficulty.difficultySeo,null);
assert.equal(reportForKeywords({keywords,ads:{...ads,geo:"ES"},now}).rows[0].volume.avgMonthlySearches,null);
assert.equal(reportForKeywords({keywords,ads:{...ads,capturedAt:"2025-01-01T00:00:00Z"},now}).rows[0].volume.avgMonthlySearches,null);
const gsc={property:"sc-domain:eldiariodelcibao.com",country:"DOM",searchType:"web",capturedAt:now,startDate:"2026-09-01",endDate:"2026-10-09",rows:[{query:sample,impressions:240,clicks:22,position:7.4}]};
const gscReport=reportForKeywords({keywords,gsc,now});
assert.equal(gscReport.rows[0].gsc.status,"OBSERVED_SITE_ONLY");
assert.equal(gscReport.rows[0].gsc.siteImpressions,240);
assert.equal(gscReport.rows[1].gsc.siteImpressions,null);
const rs=Array.from({length:10},(_,i)=>({rank:i+1,url:"https://www.gob.do/page"+i,title:i<5?sample:"Otra consulta"}));
const serp={engine:"google",geo:"DO",language:"es",capturedAt:now,queries:[{keyword:sample,results:rs}]};
const combined=reportForKeywords({keywords,gsc,ads,serp,now});
assert.equal(combined.rows[0].evidenceGate,"PARTIAL");
assert.equal(combined.rows[0].difficulty.status,"HEURISTIC_ONLY");
assert.equal(combined.rows[0].difficulty.difficultySeo,null);
assert.equal(combined.summary.strictSeoDifficultyProved,0);
assert.equal(combined.summary.pass,0);
assert.equal(combined.summary.unverified,9);
assert.equal(reportForKeywords({keywords,serp:{...serp,geo:"FR"},now}).rows[0].difficulty.status,"UNVERIFIED");
console.log("PASS ASTRA Keyword Evidence Ω: 10 keywords, strict no-fake-volume, geography, freshness, Google Ads vs SEO KD, GSC, SERP heuristic, no-false-PASS");
